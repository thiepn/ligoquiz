import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
const folder='test-results/u09-host-evidence';
async function setup(page,count=3,profile=null){
 await page.goto('/#/setup');
 await page.getByRole('combobox',{name:'Anzahl der Teams'}).selectOption(String(count));
 await page.getByRole('button',{name:'Weiter'}).click();
 await page.getByRole('button',{name:/Umfrageduell/}).click();
 if(profile)await page.getByRole('combobox',{name:'Umfang'}).selectOption(profile);
 await page.getByRole('button',{name:'Weiter'}).click();
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Spielleitung öffnen'}).click();
 await expect(page).toHaveURL(/#\/host$/);
 const host=page.locator('.ud-host');
 await expect(host.locator('.u07-phase-rail')).toBeVisible();
 return host;
}
const phase=host=>host.locator('.u07-phase-steps [aria-current="step"]');
async function noOverflow(page){
 const dims=await page.evaluate(()=>({width:globalThis.innerWidth,actual:globalThis.document.documentElement.scrollWidth}));
 expect(dims.actual).toBeLessThanOrEqual(dims.width+3);
}
test('U09 actual draft estimate stays private, only recorded teams permit rank reveal',async({page})=>{
 await mkdir(folder,{recursive:true});
 await page.setViewportSize({width:1365,height:850});
 const host=await setup(page);
 await expect(phase(host)).toContainText('Vorbereiten');
 await expect(host.locator('.u09-mode-head')).toContainText('HERKUNFT PRO AUFGABE PRÜFEN');
 await expect(host.locator('.ud-scorebar strong')).toHaveText(['0','0','0']);
 await host.getByRole('button',{name:'Aufgabenfolge bestätigen'}).click();
 await expect(host.locator('.u09-origin')).toContainText('BEISPIELDATEN – KEINE ECHTE UMFRAGE');
 await host.getByRole('button',{name:'Aufgabe veröffentlichen'}).click();
 await expect(phase(host)).toContainText('Antworten');
 await host.getByRole('button',{name:'Alle Antworten schließen'}).click();
 await expect(phase(host)).toContainText('Antworten');
 const first=host.locator('.ud-team').nth(0);
 await expect(host.locator('.u09-judging-head')).toContainText('0 / 3');
 await first.getByRole('textbox',{name:'Antwort 1'}).fill('Snacks');
 await expect(first.getByRole('combobox',{name:'Zuordnung'})).toHaveValue('1');
 await expect(first.locator('.u09-team-preview')).toContainText('20 Punkte');
 await expect(first.locator('.u09-team-preview')).toContainText('NICHT GESPEICHERT');
 await expect(host.locator('.ud-scorebar strong')).toHaveText(['0','0','0']);
 await expect(host.getByRole('button',{name:'Kategorien und Rangfolge veröffentlichen'})).toBeDisabled();
 await host.screenshot({path:folder+'/survey-draft-desktop.png'});
 await first.getByRole('button',{name:'Antwort erfassen'}).click();
 await expect(host.locator('.u09-judging-head')).toContainText('1 / 3');
 await expect(first.locator('.ud-team-head')).toContainText('Erfasst: 20 Punkte');
 await host.locator('.ud-team').nth(1).getByRole('textbox',{name:'Antwort 1'}).fill('Getränke');
 await host.locator('.ud-team').nth(1).getByRole('button',{name:'Antwort erfassen'}).click();
 await host.locator('.ud-team').nth(2).getByRole('button',{name:'Antwort erfassen'}).click();
 await expect(host.locator('.u09-reveal-gate')).toContainText('3 / 3');
 await expect(host.getByRole('button',{name:'Kategorien und Rangfolge veröffentlichen'})).toBeEnabled();
 await host.getByRole('button',{name:'Kategorien und Rangfolge veröffentlichen'}).click();
 await expect(phase(host)).toContainText('Werten');
 await expect(host.locator('.u09-ranking>li')).toHaveCount(5);
 await expect(host.locator('.u09-award-summary')).toContainText('20 Punkte vorgemerkt');
 await expect(host.locator('.u09-source-reminder')).toContainText('Fiktive Beispielrangfolge');
 await host.screenshot({path:folder+'/survey-published-ranking-desktop.png'});
 await host.getByRole('button',{name:'Teamwertungen verbindlich bestätigen'}).click();
 await expect(phase(host)).toContainText('Weiter');
 await expect(host.locator('.ud-scorebar strong')).toHaveText(['20','15','0']);
 await expect(host.locator('.u09-awards')).toContainText('20 Punkte');
});
test('U09 correction remains reasoned, explicit and auditable after published award',async({page})=>{
 const host=await setup(page);
 await host.getByRole('button',{name:'Aufgabenfolge bestätigen'}).click();
 await host.getByRole('button',{name:'Aufgabe veröffentlichen'}).click();
 await host.getByRole('button',{name:'Alle Antworten schließen'}).click();
 const teams=host.locator('.ud-team');
 await teams.nth(0).getByRole('textbox',{name:'Antwort 1'}).fill('Snacks');
 for(let i=0;i<3;i++)await teams.nth(i).getByRole('button',{name:'Antwort erfassen'}).click();
 await host.getByRole('button',{name:'Kategorien und Rangfolge veröffentlichen'}).click();
 await host.getByRole('button',{name:'Teamwertungen verbindlich bestätigen'}).click();
 await expect(host.locator('.ud-scorebar strong')).toHaveText(['20','0','0']);
 await teams.nth(0).getByRole('combobox',{name:'Zuordnung'}).selectOption('5');
 await expect(teams.nth(0).locator('.u09-team-preview')).toContainText('2 Punkte');
 await expect(host.locator('.ud-scorebar strong')).toHaveText(['20','0','0']);
 page.once('dialog',dialog=>dialog.accept('Schiedsrichterkorrektur'));
 await teams.nth(0).getByRole('button',{name:'Begründet korrigieren'}).click();
 await expect(host.locator('.ud-scorebar strong')).toHaveText(['2','0','0']);
 await expect(host.locator('.u09-awards')).toContainText('2 Punkte');
});
test('U09 375px five-team original survey works with reduced motion and no overflow',async({page})=>{
 await mkdir(folder,{recursive:true});
 await page.setViewportSize({width:375,height:812});
 await page.emulateMedia({reducedMotion:'reduce'});
 const host=await setup(page,5);
 await expect(host.locator('.u07-phase-steps>li')).toHaveCount(4);
 await noOverflow(page);
 const stage=host.getByRole('link',{name:/Beamer öffnen/});
 await expect(stage).toHaveAttribute('target','_blank');
 await expect(stage).toHaveAttribute('rel',/noopener/);
 await host.getByRole('button',{name:'Aufgabenfolge bestätigen'}).click();
 await host.getByRole('button',{name:'Aufgabe veröffentlichen'}).click();
 await expect(host.locator('.u09-clock')).toBeVisible();
 await host.getByRole('button',{name:'Alle Antworten schließen'}).click();
 await expect(host.locator('.ud-team')).toHaveCount(5);
 await host.locator('.ud-team').first().getByRole('textbox',{name:'Antwort 1'}).fill('Snacks');
 await expect(host.locator('.ud-team').first().locator('.u09-team-preview')).toContainText('20 Punkte');
 await noOverflow(page);
 await host.screenshot({path:folder+'/survey-mobile-375.png'});
});
